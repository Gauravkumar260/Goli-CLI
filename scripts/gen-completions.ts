// ─── Bash completion ──────────────────────────────────────────────────

function genBash(): string {
  const lines: string[] = [
    '# goli bash completion',
    '# Generated by scripts/gen-completions.ts — do not edit by hand.',
    '# Install: source this file in your .bashrc, or copy to /etc/bash_completion.d/goli',
    '',
    '_goli() {',
    '    local cur prev opts cmds',
    '    COMPREPLY=()',
    '    cur="${COMP_WORDS[COMP_CWORD]}"',
    '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '',
    '    # Top-level commands',
    '    cmds="wakeup doctor status audit usage commit init mcp help"',
    '',
    '    # If completing the first word after "goli", suggest commands',
    '    if [[ $COMP_CWORD -eq 1 ]]; then',
    '        COMPREPLY=( $(compgen -W "$cmds" -- "$cur") )',
    '        return 0',
    '    fi',
    '',
    '    # Subcommand-specific flags',
    '    local cmd="${COMP_WORDS[1]}"',
    '    case "$cmd" in',
  ];

  for (const cmd of COMMANDS) {
    const flags = [...GLOBAL_FLAGS, ...cmd.flags];
    const flagStr = flags.map((f) => f.long).join(' ');
    lines.push(`        ${cmd.name})`);
    lines.push(`            opts="${flagStr}"`);
    lines.push(`            COMPREPLY=( $(compgen -W "$opts" -- "$cur") )`);
    lines.push('            return 0');
    lines.push('            ;;');
  }

  lines.push('    esac');
  lines.push('');
  lines.push('    # Global flags (available for all commands)');
  lines.push('    local global_opts="' + GLOBAL_FLAGS.map((f) => f.long).join(' ') + '"');
  lines.push('    COMPREPLY=( $(compgen -W "$global_opts" -- "$cur") )');
  lines.push('    return 0');
  lines.push('}');
  lines.push('complete -F _goli goli');
  lines.push('');

  return lines.join('\n');
}

// ─── Zsh completion ───────────────────────────────────────────────────

function genZsh(): string {
  const lines: string[] = [
    '#compdef goli',
    '# goli zsh completion',
    '# Generated by scripts/gen-completions.ts — do not edit by hand.',
    '# Install: cp this file to ~/.zsh/completions/_goli && compinit',
    '',
    '_goli() {',
    '    local -a commands',
    '    commands=(',
  ];
  for (const cmd of COMMANDS) {
    lines.push(`        '${cmd.name}:${cmd.description.replace(/'/g, "'\\''")}'`);
  }
  lines.push('    )');
  lines.push('');
  lines.push('    _arguments -C \\');
  for (const f of GLOBAL_FLAGS) {
    const argPart = f.takesArg ? ':arg:' : '';
    const shortPart = f.short ? `'${f.short}[${f.description}]${argPart}' \\` : '';
    lines.push(`        '${f.long}[${f.description}]${argPart}' \\`);
    if (shortPart) lines.push(`        ${shortPart}`);
  }
  lines.push('        \'*: :->command\'');
  lines.push('');
  lines.push('    case $state in');
  lines.push('        command)');
  lines.push('            _describe \'command\' commands');
  lines.push('            ;;');
  lines.push('    esac');
  lines.push('}');
  lines.push('');
  lines.push('_goli "$@"');
  lines.push('');

  return lines.join('\n');
}

// ─── Fish completion ──────────────────────────────────────────────────

function genFish(): string {
  const lines: string[] = [
    '# goli fish completion',
    '# Generated by scripts/gen-completions.ts — do not edit by hand.',
    '# Install: cp this file to ~/.config/fish/completions/goli.fish',
    '',
    '# Commands',
  ];
  for (const cmd of COMMANDS) {
    lines.push(`complete -c goli -f -n '__fish_use_subcommand' -a '${cmd.name}' -d '${cmd.description.replace(/'/g, "\\'")}'`);
  }
  lines.push('');
  lines.push('# Global flags');
  for (const f of GLOBAL_FLAGS) {
    const argPart = f.takesArg ? ' -r' : '';
    lines.push(`complete -c goli -f -n '__fish_use_subcommand' -l '${f.long.replace(/^--/, '')}'${argPart} -d '${f.description.replace(/'/g, "\\'")}'`);
    if (f.short) {
      lines.push(`complete -c goli -f -n '__fish_use_subcommand' -s '${f.short.replace(/^-/, '')}'${argPart} -d '${f.description.replace(/'/g, "\\'")}'`);
    }
  }
  lines.push('');
  // Per-command flags
  for (const cmd of COMMANDS) {
    if (cmd.flags.length === 0) continue;
    lines.push(`# ${cmd.name} flags`);
    for (const f of cmd.flags) {
      const argPart = f.takesArg ? ' -r' : '';
      lines.push(`complete -c goli -f -n '__fish_seen_subcommand_from ${cmd.name}' -l '${f.long.replace(/^--/, '')}'${argPart} -d '${f.description.replace(/'/g, "\\'")}'`);
      if (f.short) {
        lines.push(`complete -c goli -f -n '__fish_seen_subcommand_from ${cmd.name}' -s '${f.short.replace(/^-/, '')}'${argPart} -d '${f.description.replace(/'/g, "\\'")}'`);
      }
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ─── Main ─────────────────────────────────────────────────────────────

function main(): void {
  mkdirSync(OUTPUT_DIR, { recursive: true });

  const bash = genBash();
  const zsh = genZsh();
  const fish = genFish();

  writeFileSync(resolve(OUTPUT_DIR, 'goli.bash'), bash, 'utf-8');
  writeFileSync(resolve(OUTPUT_DIR, '_goli'), zsh, 'utf-8');  // zsh convention: underscore prefix
  writeFileSync(resolve(OUTPUT_DIR, 'goli.fish'), fish, 'utf-8');

  console.log(`✓ Generated completions in ${OUTPUT_DIR}:`);
  console.log('  goli.bash  (bash)');
  console.log('  _goli      (zsh)');
  console.log('  goli.fish  (fish)');
  console.log();
  console.log(`  ${GLOBAL_FLAGS.length} global flags, ${COMMANDS.length} commands, ${COMMANDS.reduce((s, c) => s + c.flags.length, 0)} command-specific flags`);
}

main();
