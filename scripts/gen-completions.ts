/**
 * scripts/gen-completions.ts
 *
 * A3 acceptance criterion: every public CLI flag has a shell completion.
 *
 * Generates shell completion scripts for bash, zsh, and fish that cover
 * all `goli` subcommands and their flags. The completions are derived
 * from the Commander program definition (single source of truth).
 *
 * Output:
 *   completions/goli.bash  — bash completion script
 *   completions/goli.zsh   — zsh completion script
 *   completions/goli.fish  — fish completion script
 *
 * Usage:
 *   npx tsx scripts/gen-completions.ts
 *
 * Install (bash):
 *   source completions/goli.bash
 *   # or copy to /etc/bash_completion.d/goli
 *
 * Install (zsh):
 *   fpath+=(~/.zsh/completions)
 *   cp completions/_goli ~/.zsh/completions/
 *   compinit
 *
 * Install (fish):
 *   cp completions/goli.fish ~/.config/fish/completions/
 */

